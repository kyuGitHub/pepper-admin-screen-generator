// Bundles the Vercel function source (src/server/generate.ts) into one self-contained ESM file, api/generate.js.
// Vercel compiles api/*.ts per file, which breaks extensionless relative imports under "type": "module";
// a single bundled file has no relative imports and loads the same way in Vercel, Node and the Vite dev plugin.
import { build } from 'esbuild';

await build({
  entryPoints: ['src/server/generate.ts'],
  outfile: 'api/generate.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  external: ['@anthropic-ai/sdk', '@supabase/supabase-js'],
  banner: { js: '// Generated by scripts/build-api.mjs from src/server/generate.ts — do not edit.' },
  logLevel: 'warning',
});
console.log('wrote api/generate.js');
